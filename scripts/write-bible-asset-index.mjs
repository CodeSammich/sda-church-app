/**
 * Writes assets/bible/index.ts, the static require() map Metro needs to ship the
 * Bible texts in assets/bible as files (see metro.config.js) and the app needs
 * to find them (services/BundledBible.ts).
 *
 * Each collection is a folder of <book>.biblejson files plus books.biblejson,
 * such as assets/bible/cuv1919/hant. The build scripts that write a collection
 * call this afterwards; it can also be run on its own:
 *   node scripts/write-bible-asset-index.mjs
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const bibleRoot = join(root, 'assets/bible');

const collectionsIn = (folder) =>
  readdirSync(folder)
    .sort()
    .flatMap((name) => {
      const path = join(folder, name);
      if (!statSync(path).isDirectory()) return [];
      const files = readdirSync(path).filter((file) => file.endsWith('.biblejson')).sort();
      return [...(files.length ? [{ path, files }] : []), ...collectionsIn(path)];
    });

export const writeBibleAssetIndex = () => {
  const collections = collectionsIn(bibleRoot);
  const lines = [
    '// Generated by scripts/write-bible-asset-index.mjs. Do not edit by hand.',
    '// Metro ships each .biblejson file as an asset (metro.config.js), and',
    '// services/BundledBible.ts reads one when a book is opened.',
    'export const BUNDLED_BIBLE_ASSETS = {',
    ...collections.flatMap(({ path, files }) => [
      `  '${relative(bibleRoot, path).split(sep).join('/')}': {`,
      ...files.map((file) => `    '${file.replace(/\.biblejson$/, '')}': require('./${relative(bibleRoot, join(path, file)).split(sep).join('/')}'),`),
      '  },',
    ]),
    '} as const;',
    '',
    'export type BundledBibleCollection = keyof typeof BUNDLED_BIBLE_ASSETS;',
    '',
  ];
  writeFileSync(join(bibleRoot, 'index.ts'), lines.join('\n'));
  return collections.map(({ path }) => relative(bibleRoot, path));
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`Indexed ${writeBibleAssetIndex().join(', ')}.`);
}
