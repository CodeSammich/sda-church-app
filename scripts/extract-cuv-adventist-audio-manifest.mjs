#!/usr/bin/env node

/**
 * Extracts public Adventist Connect CUV asset URLs from WordPress upload HARs.
 * Only canonical filenames and public asset URLs are written to source control;
 * cookies, nonces, requests, and other HAR content are never copied.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const EXPECTED_CHAPTERS = 1189;
const FILENAME_PATTERN = /^CUV_B(?:0[1-9]|[1-5]\d|6[0-6])C\d{3}\.mp3$/;
const BOOK_CHAPTER_COUNTS = [
  50, 40, 27, 36, 34, 24, 21, 4, 31, 24, 22, 25, 29, 36, 10, 13, 10, 42,
  150, 31, 12, 8, 66, 52, 5, 48, 12, 14, 3, 9, 1, 4, 7, 3, 3, 3, 2, 14,
  4, 28, 16, 24, 21, 28, 16, 16, 13, 6, 6, 4, 4, 5, 3, 6, 4, 3, 1, 13,
  5, 5, 3, 5, 1, 1, 1, 22,
];
const expectedFilenames = new Set(
  BOOK_CHAPTER_COUNTS.flatMap((chapterCount, bookIndex) =>
    Array.from({ length: chapterCount }, (_, chapterIndex) =>
      `CUV_B${String(bookIndex + 1).padStart(2, '0')}C${String(
        chapterIndex + 1,
      ).padStart(3, '0')}.mp3`,
    ),
  ),
);
const ASSET_URL_PATTERN =
  /^https:\/\/assets\.adventistconnect\.org\/newyork2\/[^?#]+\/CUV_B\d{2}C\d{3}\.mp3$/;
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(
  repoRoot,
  'constants',
  'CuvAdventistAudioManifest.ts',
);

const [harPathArgument, ...supplementalUrls] = process.argv.slice(2);
if (!harPathArgument) {
  console.error(
    'Usage: node scripts/extract-cuv-adventist-audio-manifest.mjs <upload.har> [supplemental-url ...]',
  );
  process.exit(1);
}

const addUrl = (manifest, filename, url, source) => {
  if (!FILENAME_PATTERN.test(filename)) {
    throw new Error(`${source}: invalid canonical filename ${filename}`);
  }
  if (!expectedFilenames.has(filename)) {
    throw new Error(`${source}: filename is not a canonical Bible chapter ${filename}`);
  }
  if (!ASSET_URL_PATTERN.test(url)) {
    throw new Error(`${source}: unexpected Adventist Connect URL ${url}`);
  }
  if (path.basename(new URL(url).pathname) !== filename) {
    throw new Error(`${source}: URL filename does not match ${filename}`);
  }
  const existing = manifest.get(filename);
  if (existing && existing !== url) {
    throw new Error(`${source}: conflicting URLs for ${filename}`);
  }
  manifest.set(filename, url);
};

const harPath = path.resolve(harPathArgument);
const har = JSON.parse(await readFile(harPath, 'utf8'));
const manifest = new Map();

for (const [index, entry] of (har.log?.entries || []).entries()) {
  let responseText = entry.response?.content?.text;
  if (!responseText) continue;
  if (entry.response.content.encoding === 'base64') {
    responseText = Buffer.from(responseText, 'base64').toString('utf8');
  }
  if (!responseText.startsWith('{"success":')) continue;

  try {
    const response = JSON.parse(responseText);
    const { filename, mime, url } = response.data || {};
    if (
      response.success === true &&
      mime === 'audio/mpeg' &&
      typeof filename === 'string' &&
      typeof url === 'string' &&
      filename.startsWith('CUV_')
    ) {
      addUrl(manifest, filename, url, `HAR entry ${index}`);
    }
  } catch (error) {
    if (responseText.includes('CUV_B')) throw error;
  }
}

for (const url of supplementalUrls) {
  const filename = path.basename(new URL(url).pathname);
  addUrl(manifest, filename, url, 'supplemental URL');
}

if (manifest.size !== EXPECTED_CHAPTERS) {
  throw new Error(
    `Expected ${EXPECTED_CHAPTERS} unique URLs, found ${manifest.size}. Refusing to generate an incomplete manifest.`,
  );
}

const entries = [...manifest].sort(([left], [right]) => left.localeCompare(right));
const lines = entries.map(
  ([filename, url]) => `  ${JSON.stringify(filename)}: ${JSON.stringify(url)},`,
);
const source = `// Generated by scripts/extract-cuv-adventist-audio-manifest.mjs.\n// Contains public media URLs only; do not commit the source HAR.\n\nexport const CUV_ADVENTIST_AUDIO_URLS: Readonly<Record<string, string>> = Object.freeze({\n${lines.join('\n')}\n});\n`;

await writeFile(outputPath, source);
console.log(`Wrote ${entries.length} public audio URLs to ${outputPath}`);
